# A provider response containing exact and narrowed entries for the same identity
# must expose both raw occurrences. The C# catalog validator rejects the duplicate
# individual evidence instead of accepting the single all-accounts occurrence.
$locationsBeforeDuplicate = @($script:locations)
$script:locations += [pscustomobject]@{
    Workload = 'Applications'
    Location = $child.ToString('D')
    LocationSource = 'Entra'
    LocationType = 'Individual'
    Inclusions = @(@{ Type = 'User'; Identity = [guid]::NewGuid().ToString('D') })
    WhenChangedUTC = '2026-10-05T00:00:00Z'
}
$duplicateScopeCatalog = (Read-PurviewPolicyCatalog -TenantId $tenant).items[0]
$duplicateIndividualIds = @($duplicateScopeCatalog.individualApplicationIds |
    Where-Object { $_ -ceq $child.ToString('D') })
$duplicateAllAccountsIds = @($duplicateScopeCatalog.allAccountsApplicationIds |
    Where-Object { $_ -ceq $child.ToString('D') })
Assert-True ($duplicateIndividualIds.Count -eq 2) 'Catalog hid duplicate individual scope evidence for one agent.'
Assert-True ($duplicateAllAccountsIds.Count -eq 1) 'Narrow duplicate scope was misreported as an all-accounts target.'
$script:locations = $locationsBeforeDuplicate

$request = New-Request
& {
    Set-StrictMode -Version Latest
    Add-PurviewIndividualTarget -Request $request -Catalog $null
}
Assert-True ($script:mutations -eq 1) 'Idempotent exact readback wrote again.'

# An exact target must still be checked against the second live provider read.
# A timestamp change is enough to make the public reviewed revision stale.
$request = New-Request
$script:changeTimestampOnRead = $script:policyReads + 2
try {
    Add-PurviewIndividualTarget -Request $request -Catalog $null
    throw 'Existing target bypassed the second-read concurrency check.'
}
catch {
    if ($_.Exception.Message -ne 'ASSIGNMENT_REVIEW_STALE') { throw }
}
$script:changeTimestampOnRead = 0
Assert-True ($script:mutations -eq 1) 'Existing-target concurrency failure changed the provider.'

$childLocation = @($script:locations | Where-Object Location -eq $child.ToString('D'))[0]
$childLocation | Add-Member Exclusions @(@{ Type = 'User'; Identity = [guid]::NewGuid().ToString('D') })
$request = New-Request
try {
    Add-PurviewIndividualTarget -Request $request -Catalog $null
    throw 'Excluded existing target was broadened.'
}
catch {
    if ($_.Exception.Message -ne 'ASSIGNMENT_EXISTING_SCOPE_CONFLICT') { throw }
}
$request.reviewedRevision = '0' * 64
try {
    Add-PurviewIndividualTarget -Request $request -Catalog $null
    throw 'Stale whole-scope review was accepted.'
}
catch {
    if ($_.Exception.Message -ne 'ASSIGNMENT_REVIEW_STALE') { throw }
}
Assert-True ($script:mutations -eq 1) 'Rejected assignments changed the provider.'

# A material provider change that races the write is detected after readback. It
# remains unconfirmed and is never silently treated as a successful assignment.
$concurrentChild = [guid]::NewGuid()
$script:expectedChild = $concurrentChild
$script:materialChangeOnMutation = $true
$concurrentRequest = New-Request $concurrentChild
try {
    Add-PurviewIndividualTarget -Request $concurrentRequest -Catalog $null
    throw 'Concurrent rule change was accepted.'
}
catch {
    if ($_.Exception.Message -ne 'ASSIGNMENT_CONCURRENT_POLICY_CHANGE') { throw }
}
Assert-True ($script:mutations -eq 2) 'Concurrent-change fixture did not perform the one uncertain provider write.'

'Dual policy revisions, deterministic canonicalization, exact-target delta, sibling stability, and concurrent-change checks passed (no network).'
