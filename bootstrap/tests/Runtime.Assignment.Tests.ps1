Assert-True ($withSibling.definitionRevision -ceq $renamed.definitionRevision) 'Sibling target addition changed durable enforcement identity.'
Assert-True ($withSibling.allAccountsApplicationIds -contains $sibling.ToString('D')) 'Original exact target disappeared after sibling addition.'

$beforeMaterial = $withSibling
$script:policyMode = 'TestWithNotifications'
