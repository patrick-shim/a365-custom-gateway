function Get-DlpCompliancePolicy {
    param($Identity)
    $script:policyReads++
    $timestamp = $script:policyTimestamp
    if ($script:changeTimestampOnRead -eq $script:policyReads) {
        $timestamp = '2099-01-01T00:00:00Z'
    }
    [pscustomobject]@{
        Guid = $script:policyId
        Name = $script:policyName
        Mode = $script:policyMode
        Locations = ConvertTo-Json -InputObject $script:locations -Depth 20 -Compress
        EnforcementPlanes = $script:planes
        WhenChangedUTC = $timestamp
    }
}

function Get-DlpComplianceRule {
    param($Policy)
    $script:rules
}

function Set-DlpCompliancePolicy {
    param($Identity, $Locations, $Confirm)
    if ([guid]$Identity -ne $policyId) { throw 'Wrong policy.' }
    $delta = @($Locations | ConvertFrom-Json)
    if ($delta.Count -ne 1 -or $delta[0].Location -ne $script:expectedChild.ToString('D') -or
        $delta[0].Inclusions -or $delta[0].AddInclusions[0].Type -ne 'Tenant' -or
        $delta[0].AddInclusions[0].Identity -ne 'All') {
        throw 'Unsafe scope replacement.'
    }

    $script:mutations++
    $script:locations += New-ExactApplicationLocation $script:expectedChild
    if ($script:reorderOnMutation) {
        [array]::Reverse($script:locations)
        [array]::Reverse($script:planes)
        [array]::Reverse($script:rules)
        $script:policyTimestamp = '2026-10-05T00:00:00Z'
        foreach ($location in $script:locations) { $location.WhenChangedUTC = '2026-10-05T00:00:00Z' }
        foreach ($rule in $script:rules) { $rule.WhenChangedUTC = '2026-10-05T00:00:00Z' }
        $unrelated = @($script:locations | Where-Object Workload -eq 'Exchange')[0]
        [array]::Reverse($unrelated.Inclusions)
        [array]::Reverse($unrelated.Exclusions)
        $blocking = @($script:rules | Where-Object Name -eq 'Blocking')[0]
        $blocking.AdvancedRule = '{"and":[{"first":1,"second":2},{"third":3}]}'
    }
    if ($script:materialChangeOnMutation) {
        @($script:rules | Where-Object Name -eq 'Blocking')[0].Priority++
    }
}

function New-Request {
    param([Guid]$AgentIdentityId = $child)
    $catalog = Read-PurviewPolicyCatalog -TenantId $tenant
    @{
        tenantId = $tenant
        agentIdentityId = $AgentIdentityId
        blueprintId = $blueprint
        policyId = $policyId
        reviewedRevision = $catalog.items[0].revision
        expiresAtUtc = [DateTimeOffset]::UtcNow.AddMinutes(5)
    }
}

# The public revision retains the deployed whole-scope algorithm. The definition
# revision ignores timestamps, known set ordering, cosmetic rename, and scope.
$baseline = Read-PurviewPolicyCatalog -TenantId $tenant
$baselinePolicy = $baseline.items[0]
Assert-True ($baselinePolicy.revision -cmatch '^[0-9a-f]{64}$') 'Full policy revision is invalid.'
Assert-True ($baselinePolicy.definitionRevision -cmatch '^[0-9a-f]{64}$') 'Definition revision is invalid.'

$script:policyTimestamp = '2026-10-04T00:00:00Z'
foreach ($location in $script:locations) { $location.WhenChangedUTC = '2026-10-04T00:00:00Z' }
foreach ($rule in $script:rules) { $rule.WhenChangedUTC = '2026-10-04T00:00:00Z' }
[array]::Reverse($script:locations)
[array]::Reverse($script:planes)
[array]::Reverse($script:rules)
$blocking = @($script:rules | Where-Object Name -eq 'Blocking')[0]
$blocking.AdvancedRule = '{"and":[{"first":1,"second":2},{"third":3}]}'
$reordered = (Read-PurviewPolicyCatalog -TenantId $tenant).items[0]
Assert-True ($reordered.revision -cne $baselinePolicy.revision) 'Legacy public revision stopped observing timestamps or provider array ordering.'
Assert-True ($reordered.definitionRevision -ceq $baselinePolicy.definitionRevision) 'Provider reorder or timestamps changed the definition revision.'

$blocking.AdvancedRule = '{"and":[{"third":3},{"first":1,"second":2}]}'
$nestedArrayChanged = (Read-PurviewPolicyCatalog -TenantId $tenant).items[0]
Assert-True ($nestedArrayChanged.definitionRevision -cne $reordered.definitionRevision) 'Unknown nested array reorder was treated as equivalent.'
$blocking.AdvancedRule = '{"and":[{"first":1,"second":2},{"third":3}]}'
$nestedArrayRestored = (Read-PurviewPolicyCatalog -TenantId $tenant).items[0]
Assert-True ($nestedArrayRestored.definitionRevision -ceq $reordered.definitionRevision) 'Equivalent dictionary-key reorder did not restore enforcement identity.'

$script:policyName = 'Cosmetic rename'
