function Assert-True {
    param([bool]$Condition, [string]$Message)
    if (-not $Condition) { throw $Message }
}

function New-ExactApplicationLocation {
    param([Guid]$ApplicationId)
    [pscustomobject]@{
        Workload = 'Applications'
        Location = $ApplicationId.ToString('D')
        LocationSource = 'Entra'
        LocationType = 'Individual'
        Inclusions = @(@{ Type = 'Tenant'; Identity = 'All' })
        WhenChangedUTC = '2026-10-03T00:00:00Z'
    }
}

