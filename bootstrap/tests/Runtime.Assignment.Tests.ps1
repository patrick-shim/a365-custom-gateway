function New-TestRule {
    param([Guid]$Id, [string]$Name, [int]$Priority, [bool]$Disabled = $false)
    [pscustomobject]@{
        Guid = $Id
        Name = $Name
        Disabled = $Disabled
        Priority = $Priority
        AdvancedRule = '{"and":[{"second":2,"first":1},{"third":3}]}'
        ContentContainsSensitiveInformation = @(@{ name = 'Synthetic'; minCount = 1 })
        RestrictAccess = @(@{ setting = 'UploadText'; value = $(if ($Disabled) { 'Audit' } else { 'Block' }) })
        WhenChangedUTC = '2026-10-03T00:00:00Z'
    }
}

$canonicalOne = ConvertTo-PurviewCanonicalJson @{
    nested = [ordered]@{ first = 1; second = 2 }
    items = @(@{ name = 'second' }, @{ name = 'first' })
}
$canonicalTwo = ConvertTo-PurviewCanonicalJson @{
    items = @(@{ name = 'second' }, @{ name = 'first' })
    nested = [ordered]@{ second = 2; first = 1 }
}
Assert-True ($canonicalOne -ceq $canonicalTwo) 'Dictionary key order changed canonical policy JSON.'
$canonicalArrayReordered = ConvertTo-PurviewCanonicalJson @{
    nested = [ordered]@{ second = 2; first = 1 }
    items = @(@{ name = 'first' }, @{ name = 'second' })
}
Assert-True ($canonicalOne -cne $canonicalArrayReordered) 'Unknown nested array order was discarded.'

